"""Render the handoff artifact: Markdown note + JSON sidecar."""
from __future__ import annotations

import json
from typing import Dict, List

from .model import Handoff, HandoffItem, SECTIONS


def _now_section(handoff: Handoff) -> List[str]:
    """NOW = what the next agent needs as current state: goal + completed
    work + the most recent decision. Deterministic from extracted items."""
    lines: List[str] = []
    if handoff.goal:
        lines.append(f"Goal: {handoff.goal}")
    done = [i for i in handoff.items if i.section == "DONE" and i.status == "active"]
    for item in done[-5:]:
        lines.append(f"Completed: {item.text}")
    decided = [i for i in handoff.items if i.section == "DECIDED" and i.status == "active"]
    if decided:
        lines.append(f"Latest decision: {decided[-1].text}")
    sup = [i for i in handoff.items if i.status == "superseded"]
    for item in sup[-3:]:
        other = handoff.items[item.superseded_by] if item.superseded_by is not None else None
        if other is not None:
            lines.append(f"Superseded: {item.text}  → now: {other.text}")
    if not lines:
        lines.append("(no current-state facts extracted)")
    return lines


def _items_by_section(handoff: Handoff) -> Dict[str, List[HandoffItem]]:
    out: Dict[str, List[HandoffItem]] = {s: [] for s in SECTIONS}
    for item in handoff.items:
        if item.status in ("active", "stale") and item.section in out:
            out[item.section].append(item)
    return out


def render_markdown(handoff: Handoff, coverage: Dict | None = None) -> str:
    """Render the note the next agent reads first."""
    L: List[str] = []
    L.append(f"# Handoff — {handoff.session_id} ({handoff.source})")
    L.append("")
    L.append(f"> Generated by handover from `{handoff.transcript_path}`")
    L.append(f"> on {handoff.generated_at}. Machine-readable sidecar: `handoff.json`.")
    if handoff.cwd:
        L.append(f"> Working directory: `{handoff.cwd}`")
    if coverage:
        L.append(f"> Coverage audit: {coverage['score']:.0%} "
                 f"({coverage['captured']}/{coverage['total']} decision markers captured)")
    L.append("")
    L.append("## NOW")
    L.append("")
    for line in _now_section(handoff):
        L.append(f"- {line}")
    L.append("")

    by_section = _items_by_section(handoff)
    for section in ("NEXT", "DECIDED", "REJECTED", "FAILED", "DON'T"):
        items = by_section.get(section, [])
        if section == "DON'T":
            L.append("## DON'T")
        else:
            L.append(f"## {section}")
        L.append("")
        if not items:
            L.append("- (none)")
        for item in items:
            tag = ""
            if item.status == "stale":
                tag = " [STALE]"
            L.append(f"- {item.text}{tag}")
        L.append("")

    if handoff.warnings:
        L.append("## NOTES")
        L.append("")
        for w in handoff.warnings:
            L.append(f"- {w}")
        L.append("")

    L.append("---")
    L.append("_Written for the next agent, whatever vendor it runs on. "
             "Facts above are extracted from the transcript; "
             "verify anything load-bearing before acting on it._")
    L.append("")
    return "\n".join(L)


def render_json(handoff: Handoff) -> str:
    return json.dumps(handoff.to_dict(), indent=2, ensure_ascii=False)


def write_artifact(handoff: Handoff, out_dir: str, coverage: Dict | None = None) -> Dict[str, str]:
    """Write handoff.md + handoff.json into out_dir. Returns paths."""
    import os
    os.makedirs(out_dir, exist_ok=True)
    md_path = os.path.join(out_dir, "handoff.md")
    json_path = os.path.join(out_dir, "handoff.json")
    with open(md_path, "w", encoding="utf-8") as fh:
        fh.write(render_markdown(handoff, coverage))
    with open(json_path, "w", encoding="utf-8") as fh:
        fh.write(render_json(handoff))
    return {"markdown": md_path, "json": json_path}
